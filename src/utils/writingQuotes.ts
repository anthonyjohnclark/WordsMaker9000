export function formatWritingQuote(quote: WritingQuote): string {
  return `“${quote.text}” — ${quote.author}`;
}

export function getRandomWritingQuote(
  random: () => number = Math.random,
): WritingQuote {
  const randomValue = Math.max(0, Math.min(random(), 1 - Number.EPSILON));
  return WRITING_QUOTES[Math.floor(randomValue * WRITING_QUOTES.length)];
}
